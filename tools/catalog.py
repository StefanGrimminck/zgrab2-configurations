#!/usr/bin/env python3
"""Generate CATALOG.md from the INI files, or check that it is current.

    python3 tools/catalog.py          # rewrite CATALOG.md
    python3 tools/catalog.py --check  # exit 1 if CATALOG.md is out of date

Every row comes from the config itself: the module section, name, port, the
request (endpoint, banner probe or module flag) and the first sentence of the
leading comment. Edit the INI, then regenerate; never edit CATALOG.md by hand.
"""
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "CATALOG.md")


def parse(path):
    """Return the leading comment and the list of (module, options) sections."""
    text = open(path, encoding="utf-8").read()
    comment = []
    for line in text.splitlines():
        if line.startswith("#"):
            comment.append(line.lstrip("#").strip())
        else:
            break
    sections = []
    module, opts = None, {}
    for line in text.splitlines():
        m = re.match(r"^\[([A-Za-z0-9 ]+)\]\s*$", line)
        if m:
            if module:
                sections.append((module, opts))
            module, opts = m.group(1), {}
            continue
        m = re.match(r"^([a-z0-9-]+)\s*=\s*(.*)$", line)
        if module and m:
            opts[m.group(1)] = m.group(2).strip().strip('"')
    if module:
        sections.append((module, opts))
    return " ".join(comment), sections


def first_sentence(comment):
    if comment.startswith("CVE-") and "  -  " in comment:
        comment = comment.split("  -  ", 1)[1]
    m = re.match(r"(.+?[.:])(\s|$)", comment)
    return (m.group(1) if m else comment).rstrip(":.")


def request(module, opts):
    if module == "http":
        method = opts.get("method", "GET")
        req = f"{method} {opts.get('endpoint', '/')}"
        if "custom-headers-names" in opts:
            req += f" (header {opts['custom-headers-names']})"
        return req
    if module == "banner" and "probe" in opts:
        return "banner: " + opts["probe"].replace("\\\\r\\\\n", "").replace("\\r\\n", "")
    flags = [k for k, v in opts.items() if k not in ("name", "port", "trigger") and v in ("true", "")]
    return f"{module} module" + (f" ({', '.join(flags)})" if flags else "")


def cell(s):
    return s.replace("|", "\\|")


def row(path, module, opts, desc, cve=None):
    rel = os.path.relpath(path, ROOT)
    name = os.path.basename(path)
    cols = []
    if cve:
        cols.append(cve)
    cols += [f"[`{name}`]({rel})", opts.get("port", "-"), f"`{cell(request(module, opts))}`", cell(desc)]
    return "| " + " | ".join(cols) + " |"


def cve_key(cve):
    y, n = cve.split("-")[1:]
    return int(y), int(n)


def build():
    out = ["# Catalog", "",
           "Generated by `tools/catalog.py` from the INI files. Do not edit by hand.", ""]

    base = sorted(glob.glob(os.path.join(ROOT, "base-configurations", "*.ini")))
    out += ["## Base configurations", "",
            "One file per ZGrab2 module, with the module's options listed as comments.", "",
            "| Config | Module | Port |", "| --- | --- | --- |"]
    for p in base:
        if os.path.basename(p).startswith("all"):
            continue
        _, secs = parse(p)
        mod, opts = secs[0]
        out.append(f"| [`{os.path.basename(p)}`]({os.path.relpath(p, ROOT)}) | {mod} | {opts.get('port', '-')} |")
    out += ["", "`all.ini` and `all_trigger-on-port.ini` bundle every module into one scan.", ""]

    groups = [
        ("Service discovery", "service-discovery", "Fingerprints a product on its usual port."),
        ("Misconfigurations and exposures", "vulnerabilities/misconfigurations",
         "Detects a dangerous default or an exposed file or API."),
    ]
    for title, folder, intro in groups:
        files = sorted(glob.glob(os.path.join(ROOT, folder, "*.ini")))
        out += [f"## {title}", "", f"{intro} {len(files)} configs.", "",
                "| Config | Port | Request | What it finds |", "| --- | --- | --- | --- |"]
        for p in files:
            comment, secs = parse(p)
            for mod, opts in secs:
                out.append(row(p, mod, opts, first_sentence(comment)))
        out.append("")

    files = glob.glob(os.path.join(ROOT, "vulnerabilities", "cve", "*.ini"))
    rows = []
    for p in files:
        comment, secs = parse(p)
        cves = re.findall(r"CVE-\d{4}-\d+", comment.split("  -  ")[0]) or ["-"]
        mod, opts = secs[0]
        rows.append((cve_key(cves[0]) if cves[0] != "-" else (0, 0),
                     row(p, mod, opts, first_sentence(comment), ", ".join(cves))))
    out += ["## CVE fingerprints", "",
            "Identifies a product affected by a CVE, and its version where the service "
            "publishes one, without exploiting anything. "
            f"{len(files)} configs.", "",
            "| CVE | Config | Port | Request | Product |", "| --- | --- | --- | --- | --- |"]
    out += [r for _, r in sorted(rows)]
    out.append("")
    return "\n".join(out)


if __name__ == "__main__":
    text = build()
    if "--check" in sys.argv:
        current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if current != text:
            print("CATALOG.md is out of date; run: python3 tools/catalog.py")
            sys.exit(1)
        print("CATALOG.md is current")
    else:
        open(OUT, "w", encoding="utf-8").write(text)
        print("wrote", os.path.relpath(OUT))
